const SIGNATURE: u32 = u32::from_le_bytes(*b"IDST");

bitflags! {
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
    #[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
    pub struct ModelFlags: u32 {
        const AUTOGENERATED_HITBOX = 1 << 0;
        const USES_ENV_CUBEMAP = 1 << 1;
        const FORCE_OPAQUE = 1 << 2;
        const TRANSLUCENT_TWO_PASS = 1 << 3;
        const STATIC_PROP = 1 << 4;
        const USES_FB_TEXTURE = 1 << 5;
        const HAS_SHADOW_LOD = 1 << 6;
        const USES_BUMPMAPPING = 1 << 7;
        const USE_SHADOW_LOD_MATERIALS = 1 << 8;
        const OBSOLETE = 1 << 9;
        const UNUSED = 1 << 10;
        const NO_FORCED_FADE = 1 << 11;
        const FORCE_PHONEME_CROSSFADE = 1 << 12;
        const CONSTANT_DIRECTIONAL_LIGHT_DOT = 1 << 13;
        const FLEXES_CONVERTED = 1 << 14;
        const BUILT_IN_PREVIEW_MODE = 1 << 15;
        const AMBIENT_BOOST = 1 << 16;
        const DO_NOT_CAST_SHADOWS = 1 << 17;
        const CAST_TEXTURE_SHADOWS = 1 << 18;
        const SUBDIVISION_SURFACE = 1 << 19;
        const NO_ANIM_EVENTS = 1 << 20;
        const VERT_ANIM_FIXED_POINT_SCALE = 1 << 21;
        const EXTRA_VERTEX_DATA = 1 << 26;
    }
}

#[derive(Debug, Clone, PartialEq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Header {
    /// 44 through 49
    pub version: i32,
    pub checksum: u32,
    pub name: String,
    pub eye_position: Vec3,
    pub illumination_position: Vec3,
    pub hull_min: Vec3,
    pub hull_max: Vec3,
    pub view_min: Vec3,
    pub view_max: Vec3,
    pub flags: ModelFlags,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Mdl {
    pub header: Header,
    pub bones: Vec<Bone>,
    pub bone_controllers: Vec<BoneController>,
    pub hitbox_sets: Vec<HitboxSet>,
    pub animations: Vec<Animation>,
    pub sequences: Vec<Sequence>,
    pub materials: Vec<Material>,
    /// `$cdmaterials` directories, searched in order
    pub material_directories: Vec<String>,
    /// Skin families; each maps a mesh material slot to an index into `materials`
    pub skins: Vec<Vec<usize>>,
    pub body_parts: Vec<BodyPart>,
}

impl Mdl {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self> {
        let r = Reader::new(bytes, FileKind::Mdl);
        let mut c = r.at(0, "header")?;
        let signature = c.read_u32()?;
        if signature != SIGNATURE {
            return Err(Error::InvalidSignature {
                file: FileKind::Mdl,
                expected: SIGNATURE,
                actual: signature,
            });
        }

        let version = c.read_i32()?;
        if !(44..=49).contains(&version) {
            return Err(Error::UnsupportedVersion { file: FileKind::Mdl, version });
        }

        let checksum = c.read_u32()?;
        let name = r.fixed_string(12, 64, "header")?;
        c.skip(64)?; // name, already read above as a fixed string

        let length = c.read_i32()?;
        if usize::try_from(length).ok() != Some(r.len()) {
            return Err(r.invalid("declared length", length, "must match the file size"));
        }

        let header = Header {
            version,
            checksum,
            name,
            eye_position: c.read_vec3()?,
            illumination_position: c.read_vec3()?,
            hull_min: c.read_vec3()?,
            hull_max: c.read_vec3()?,
            view_min: c.read_vec3()?,
            view_max: c.read_vec3()?,
            flags: ModelFlags::from_bits_retain(c.read_u32()?),
        };

        // (count, offset) pairs from here on, offsets count from byte 0
        let bones = (c.read_i32()?, c.read_i32()?);
        let bone_controllers = (c.read_i32()?, c.read_i32()?);
        let hitbox_sets = (c.read_i32()?, c.read_i32()?);
        let animations = (c.read_i32()?, c.read_i32()?);
        let sequences = (c.read_i32()?, c.read_i32()?);

        c.skip(8)?; // activitylistversion, eventsindexed

        let materials = (c.read_i32()?, c.read_i32()?);
        let material_directories = (c.read_i32()?, c.read_i32()?);
        let skin_reference_count = r.nonnegative(c.read_i32()?, "skin reference count")?;
        let skins = (c.read_i32()?, c.read_i32()?);
        let body_parts = (c.read_i32()?, c.read_i32()?);

        let controller_count = r.nonnegative(bone_controllers.0, "bone controllers")?;
        let bones = skeleton::parse_bones(r, bones, controller_count)?;
        let bone_controllers = skeleton::parse_bone_controllers(r, bone_controllers, bones.len())?;
        let hitbox_sets = skeleton::parse_hitbox_sets(r, hitbox_sets, bones.len())?;
        let animations = animation::parse_animations(r, animations, bones.len())?;
        let sequences = animation::parse_sequences(r, sequences, animations.len())?;
        let materials = model::parse_materials(r, materials)?;
        let material_directories = model::parse_material_directories(r, material_directories)?;
        let skins = model::parse_skins(r, skins, skin_reference_count, materials.len())?;
        let body_parts = model::parse_body_parts(r, body_parts, skin_reference_count)?;

        Ok(Self {
            header,
            bones,
            bone_controllers,
            hitbox_sets,
            animations,
            sequences,
            materials,
            material_directories,
            skins,
            body_parts,
        })
    }

    pub fn open(path: impl AsRef<Path>) -> Result<Self> {
        let path = path.as_ref();
        let bytes = fs::read(path).map_err(|source| Error::io(path, source))?;
        Self::from_bytes(&bytes)
    }

    /// Index of the sequence with this name, compared case-insensitively
    pub fn sequence_by_name(&self, name: &str) -> Option<usize> {
        self.sequences
            .iter()
            .position(|sequence| sequence.name.eq_ignore_ascii_case(name))
    }

    /// Index into `materials` for a mesh material slot in skin family `skin`
    pub fn material_index(&self, skin: usize, slot: usize) -> Result<usize> {
        let family = self
            .skins
            .get(skin)
            .ok_or(Error::index("skin family", skin, self.skins.len()))?;

        family
            .get(slot)
            .copied()
            .ok_or(Error::index("skin material slot", slot, family.len()))
    }

    /// VMT paths for `material`, one per `$cdmaterials` directory, relative to `materials/`
    pub fn material_path_candidates(&self, material: usize) -> Result<Vec<String>> {
        let material =
            self.materials
                .get(material)
                .ok_or(Error::index("material", material, self.materials.len()))?;

        if self.material_directories.is_empty() {
            return Ok(vec![material_path("", &material.name)]);
        }

        Ok(self
            .material_directories
            .iter()
            .map(|directory| material_path(directory, &material.name))
            .collect())
    }
}

/// Lowercase, forward slashes, no leading slash; `directory` may be empty
pub(crate) fn material_path(directory: &str, name: &str) -> String {
    // todo: prob improve idk?
    // cdmaterials come straight from the QC, so expect stuff like "Garmezon\Iqtestmap\"
    let directory = directory.trim_matches(['/', '\\']);
    let name = name.trim_start_matches(['/', '\\']);
    let path = if directory.is_empty() { name.to_owned() } else { format!("{directory}/{name}") };
    path.replace('\\', "/").to_ascii_lowercase()
}
